-- Crew profiles (#49): a member who wants to be found by owners says their level, where they sail and when, and
-- something about their experience. Having one is opting in; deleting the member deletes it.
create table crew_profiles (
    id bigint generated by default as identity primary key,
    user_id bigint not null unique references users on delete cascade,
    level_rank integer not null,
    region varchar(255) not null
        check (region in ('EAST_COAST', 'SOUTH_COAST', 'WEST_COUNTRY', 'CHANNEL_ISLANDS', 'WALES_AND_IRISH_SEA',
                          'WEST_SCOTLAND', 'EAST_SCOTLAND_AND_NORTH_EAST', 'IRELAND', 'NORTHERN_EUROPE',
                          'BISCAY_AND_IBERIA', 'MEDITERRANEAN', 'ATLANTIC_ISLANDS', 'CARIBBEAN', 'NORTH_AMERICA',
                          'CENTRAL_AND_SOUTH_AMERICA', 'AFRICA_AND_INDIAN_OCEAN', 'ASIA', 'PACIFIC',
                          'AUSTRALIA_AND_NEW_ZEALAND')),
    experience varchar(1000) not null,
    last_updated date not null
);

create table crew_profile_availability (
    crew_profile_id bigint not null references crew_profiles on delete cascade,
    frequency varchar(255) not null check (frequency in ('WEEKDAYS', 'WEEKENDS', 'HOLIDAYS', 'LONG_TERM', 'TRIP')),
    primary key (crew_profile_id, frequency)
);
