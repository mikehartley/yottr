-- The members who sail on a boat, as its owner knows them (CrewMember). A member asks to join, and is in the crew
-- once the owner accepts. Deleting the listing or the member removes the row.
create table boat_crew (
    id bigint generated by default as identity primary key,
    boat_id bigint not null references boats on delete cascade,
    user_id bigint not null references users on delete cascade,
    on_board boolean not null,
    asked_on date not null,
    joined_on date,
    unique (boat_id, user_id)
);

create index boat_crew_user on boat_crew (user_id);
