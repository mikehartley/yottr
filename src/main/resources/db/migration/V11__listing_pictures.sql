-- Pictures on listings, each kept twice as JPEG: scaled down to fit the listing's page, and as a thumbnail for the
-- cards. Deleting a listing removes its pictures. The first picture is the one with the lowest position.
create table listing_pictures (
    id bigint generated by default as identity primary key,
    boat_id bigint not null references boats on delete cascade,
    position integer not null,
    width integer not null,
    height integer not null,
    image bytea not null,
    thumbnail_width integer not null,
    thumbnail_height integer not null,
    thumbnail bytea not null
);

create index listing_pictures_boat on listing_pictures (boat_id, position);
